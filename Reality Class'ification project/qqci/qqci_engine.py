# ---------------------------------------------------------------------------
# THE ADDRESS: the interrogative path IS the identity.
# Compositional, ordered, non-commutative. Q4.q5 != Q5.q4.
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class QqciAddress:
    path: Tuple[Plane, ...]
    language: int = 0  # 0 = language-agnostic convergence root

    def __post_init__(self):
        if not self.path:
            raise ValueError("An address requires at least one plane.")

    @staticmethod
    def of(*planes: Plane, language: int = 0) -> "QqciAddress":
        return QqciAddress(tuple(planes), language)

    def drill(self, nxt: Plane) -> "QqciAddress":
        """The +i operator: descend one interrogative deeper."""
        return QqciAddress(self.path + (nxt,), self.language)

    def ascend(self) -> "QqciAddress":
        """Up-channel move. Root addresses return themselves."""
        if len(self.path) > 1:
            return QqciAddress(self.path[:-1], self.language)
        return self

    def in_language(self, language: int) -> "QqciAddress":
        return QqciAddress(self.path, language)

    @property
    def depth(self) -> int:
        return len(self.path)

    @property
    def root(self) -> Plane:
        """The domain being operated over."""
        return self.path[0]

    @property
    def leaf(self) -> Plane:
        """The operating interrogative."""
        return self.path[-1]

    @property
    def canonical(self) -> str:
        head = f"Q{int(self.path[0])}"
        tail = "".join(f".q{int(p)}" for p in self.path[1:])
        return f"L{self.language}:{head}{tail}"

    def __str__(self) -> str:
        return self.canonical


def axomic_id(address: QqciAddress, payload: str) -> str:
    """
    Deterministic content-addressed identity. Same address + payload = same ID,
    always. This is what makes Query IS the Write idempotent. No randomness.
    """
    h = hashlib.sha256(f"{address.canonical}|{payload}".encode("utf-8"))
    return h.hexdigest()[:16]


# ---------------------------------------------------------------------------
# SIGNED SPAN: every concept carries its own contextual range.
# love = (-love, ~love, +love) with magnitude.
# Antonyms are poles of one axis, not separate points.
# ---------------------------------------------------------------------------

@dataclass
class SignedSpan:
    negative_pole: str
    positive_pole: str
    position: float = 0.0   # -1.0 .. +1.0, where the claim sits on the axis
    magnitude: float = 0.0  # intensity, 0.0 .. 1.0

    def read(self) -> str:
        if self.position < -0.33:
            return self.negative_pole
        if self.position > 0.33:
            return self.positive_pole
        return f"~{self.positive_pole}"

    def signed_value(self) -> float:
        return self.position * self.magnitude


# ---------------------------------------------------------------------------
# COHERENCE: a 7-vector, never a scalar.
# A scalar cannot disagree with itself, so a scalar cannot detect false fill.
# ---------------------------------------------------------------------------

@dataclass
class CoherenceVector:
    scores: Dict[Plane, float] = field(default_factory=dict)

    def __post_init__(self):
        for p in Plane:
            self.scores.setdefault(p, 0.0)

    def __getitem__(self, p: Plane) -> float:
        return self.scores[p]

    def __setitem__(self, p: Plane, v: float) -> None:
        self.scores[p] = v

    @property
    def net(self) -> float:
        return sum(self.scores.values()) / len(self.scores)

    @property
    def active(self) -> Dict[Plane, float]:
        return {p: v for p, v in self.scores.items() if v > 0.0}

    @property
    def disagreement(self) -> float:
        """
        Max pairwise divergence across ACTIVE planes. Planes that cast no ray
        are silent, not dissenting: an unengaged plane must not be read as
        disagreement, or every sparse observation would look like false fill.
        """
        act = list(self.active.values())
        if len(act) < 2:
            return 0.0
        return max(act) - min(act)

    def mix_weights(self) -> Dict[Plane, float]:
        """Interpretable mixing: '40% Q4, 30% Q6, 30% Q1'."""
        total = sum(self.scores.values())
        if total <= 0:
            return {p: 0.0 for p in Plane}
        return {p: v / total for p, v in self.scores.items()}

    def readout(self, threshold: float = 0.01) -> str:
        w = self.mix_weights()
        parts = [
            f"{int(round(v * 100))}% {PLANE_NAMES[p].split('/')[0]}"
            for p, v in sorted(w.items(), key=lambda kv: -kv[1])
            if v > threshold
        ]
        return ", ".join(parts) if parts else "(empty)"


# ---------------------------------------------------------------------------
# THE CONTEXTUAL MIN-MAX GATE (replaces GELU)
#
# GELU gates on absolute magnitude with a shape identical everywhere.
# This gates on relative position within the pool's own observed range, so:
#   - it is smooth while the pool is disordered (wide range, mushy positions)
#   - it sharpens toward a hard staircase gate as the pool orders
#   - fill is detectable as range convergence, not a magic constant
#   - candidates that land between resolvable positions are IN_GAP: drill
# ---------------------------------------------------------------------------

@dataclass
class ContextualRange:
    lo: float = 0.0
    hi: float = 0.0
    n: int = 0
    _prev_width: float = -1.0
    _stable_ticks: int = 0

    def expand(self, values: Iterable[float]) -> None:
        vals = list(values)
        if not vals:
            return
        if self.n == 0:
            self.lo, self.hi = min(vals), max(vals)
        else:
            self.lo = min(self.lo, min(vals))
            self.hi = max(self.hi, max(vals))
        self.n += len(vals)

    @property
    def width(self) -> float:
        return self.hi - self.lo

    def tick(self, tol: float = 1e-6) -> None:
        """Record whether the range moved this pass. Stability implies fill."""
        if self._prev_width >= 0 and abs(self.width - self._prev_width) <= tol:
            self._stable_ticks += 1
        else:
            self._stable_ticks = 0
        self._prev_width = self.width

    @property
    def converged(self) -> bool:
        return self._stable_ticks >= 1

    def position_of(self, value: float) -> float:
        """Normalised position in range: 0.0 at min, 1.0 at max. Dimensionless."""
        if self.width <= 1e-12:
            return 1.0 if self.n else 0.0
        return (value - self.lo) / self.width


def gate(value: float, rng: ContextualRange, sharpness: float,
         gap_band: Tuple[float, float] = (0.40, 0.60)) -> Tuple[float, ModalPosition]:
    """
    Returns (gated_value, modal_position).

    sharpness in [0,1]: 0 = fully soft (early accretion, gradients flow),
    1 = hard staircase gate (pool ordered, below-threshold contributes zero).
    The hard gate is the LIMIT of the soft gate, not an imposed alternative.
    """
    pos = rng.position_of(value)

    # Soft: pass through relative position. Hard: binary threshold at midpoint.
    soft = pos
    hard = 1.0 if pos >= 0.5 else 0.0
    gated = (1.0 - sharpness) * soft + sharpness * hard

    if gap_band[0] <= pos <= gap_band[1] and sharpness < 0.75:
        modal = ModalPosition.IN_GAP     # ambiguity descends, never snaps
    elif pos >= 0.85:
        modal = ModalPosition.ARE
    elif pos >= 0.5:
        modal = ModalPosition.CAN_BE
    elif pos >= 0.15:
        modal = ModalPosition.NOT_REALLY
    else:
        modal = ModalPosition.NOT_ALL

    return gated, modal


