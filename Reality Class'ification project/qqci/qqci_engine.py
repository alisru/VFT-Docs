# TRUTHSTATE: the carved hole, the document template, the bounded pool.
# ---------------------------------------------------------------------------

class MeaningMetaRegistry:
    """
    The ADDRESS BOOK. Port of MeaningMetaRegistry from {Meaning}.cs.

    This is a separate concern from MeaningRegistry and both must exist:
      MeaningRegistry     content-addressed. Answers "what does this mean?"
                          Identity is the plane vector and the interrogative
                          path. This is the semantic space.
      MeaningMetaRegistry scale-indexed. Answers "where does this node sit?"
                          Language, rank, temporal, word. This is the filing
                          system, and it carries no meaning at all: it is
                          never indexed by plane, since plane is a system-A
                          (Qqci form) coordinate, not a filing key.

    Collapsing the two was a mistake: it made the scale layers look like
    semantic dimensions, which is the category error that produced the
    six-nested-dictionaries design in the first place.

    The original nested the six layers, so a lookup was six dereferences and a
    miss anywhere returned null. This uses parallel inverted indices instead,
    so any SUBSET of coordinates can be queried (the original required all six
    or none) and every lookup is O(1) per index plus a set intersection.
    """

    def __init__(self) -> None:
        self._by_axomic: Dict[str, Meaning] = {}
        self._by_language: Dict[int, set] = {}
        self._by_rank: Dict[TensorRank, set] = {}
        self._by_temporal: Dict[int, set] = {}
        self._by_word: Dict[str, set] = {}
        self._by_definitive: Dict[str, set] = {}

    # --- AddMeaning, but the coordinates are read off the node ---
    def add_meaning(self, m: Meaning) -> str:
        axid = m.axomic_id
        self._by_axomic[axid] = m
        self._by_language.setdefault(m.address.language, set()).add(axid)
        self._by_rank.setdefault(m.rank, set()).add(axid)
        self._by_temporal.setdefault(m.carved_at, set()).add(axid)
        self._by_word.setdefault(m.word, set()).add(axid)
        self._by_definitive.setdefault(m.definitive or m.word, set()).add(axid)
        return axid

    # --- GetMeaning, but any subset of coordinates is a legal query ---
    # No root_plane parameter: plane is a system-A (Qqci form) coordinate,
    # not a filing key. Querying by plane belongs to MeaningRegistry /
    # CoherenceVector, never to this filing index.
    def get_meaning(self, *, axomic_id: Optional[str] = None,
                    language: Optional[int] = None,
                    rank: Optional[TensorRank] = None,
                    temporal: Optional[int] = None,
                    word: Optional[str] = None,
                    definitive: Optional[str] = None) -> List[Meaning]:
        if axomic_id is not None:
            m = self._by_axomic.get(axomic_id)
            return [m] if m else []

        sets = []
        if language is not None:
            sets.append(self._by_language.get(language, set()))
        if rank is not None:
            sets.append(self._by_rank.get(rank, set()))
        if temporal is not None:
            sets.append(self._by_temporal.get(temporal, set()))
        if word is not None:
            sets.append(self._by_word.get(word, set()))
        if definitive is not None:
            sets.append(self._by_definitive.get(definitive, set()))

        if not sets:
            return list(self._by_axomic.values())
        hits = set.intersection(*sets) if len(sets) > 1 else sets[0]
        return [self._by_axomic[a] for a in sorted(hits)]

    # --- the two convenience lookups the original had ---
    def get_by_word(self, word: str) -> List[Meaning]:
        return self.get_meaning(word=word)

    def get_by_meaning(self, definitive: str) -> List[Meaning]:
        """
        The original scanned all six nested levels to find one match and
        returned the first. This is an index hit and returns ALL matches,
        because several words legitimately share a definitive meaning: that
        is what an equivalence class IS, and returning only the first
        discards the collapse.
        """
        return self.get_meaning(definitive=definitive)

    # --- what the flat original could not answer at all ---
    def plane_census(self) -> Dict[Plane, int]:
        """
        How many stored nodes are rooted at each plane. A read-only report
        over each node's own system-A address, computed on demand rather
        than maintained as a filing index: the meta-registry does not
        organise storage by plane, it only reports on what is stored.
        """
        counts: Dict[Plane, int] = {p: 0 for p in Plane}
        for m in self._by_axomic.values():
            counts[m.address.root] += 1
        return counts

    def rank_census(self) -> Dict[TensorRank, int]:
        return {r: len(self._by_rank.get(r, set())) for r in TensorRank}

    @property
    def size(self) -> int:
        return len(self._by_axomic)


@dataclass
class TruthState:
    address: QqciAddress
    budget: int = 7
    tolerance: float = 0.15
    state: FillState = FillState.CARVED
    pool: List[Meaning] = field(default_factory=list)
    slots: Dict[Plane, Meaning] = field(default_factory=dict)
    parent: Optional["TruthState"] = None
    children: List["TruthState"] = field(default_factory=list)
    rng: ContextualRange = field(default_factory=ContextualRange)
    coherence: CoherenceVector = field(default_factory=CoherenceVector)
    engagement: CoherenceVector = field(default_factory=CoherenceVector)

    # --- Excavation: the hole pulls material in. ---
    def accrete(self, m: Meaning, engagement: float = 1.0,
                assertion: float = 1.0) -> None:
        """
        ENGAGEMENT is how strongly this plane is involved (the action's plane
        signature). ASSERTION is what the plane says about the claim.

        These are different quantities and conflating them was a real bug: a
        plane weakly engaged is SILENT, not DISSENTING. Only assertions can
        disagree, so only assertions feed the false-fill detector. Engagement
        feeds the interpretable mix readout.
        """
        if self.state == FillState.FUNDAMENTAL:
            return  # TBE is terminal: irreducible units admit nothing further
        if self.state == FillState.FILLED:
            # A fill is PROVISIONAL, not sealed. Late dissent must be able to
            # reopen it, or false fill becomes undetectable the moment it is
            # marked resolved, which is the failure mode this whole mechanism
            # exists to catch. Agreeable material adds nothing to a filled
            # hole; dissenting material reopens it.
            p_existing = self.coherence[m.address.root]
            if p_existing != 0.0 and assertion >= p_existing:
                return
        self.state = FillState.ACCRETING
        self.pool.append(m)
        self.rng.expand([engagement])
        # Material settles into the sub-basin of its root plane.
        self.slots.setdefault(m.address.root, m)
        p = m.address.root
        self.engagement[p] = max(self.engagement[p], engagement)
        # Multiple observers of one plane: keep the WEAKEST assertion, so a
        # single dissenting vantage is not averaged away by agreeable ones.
        prev = self.coherence[p]
        self.coherence[p] = assertion if prev == 0.0 else min(prev, assertion)

    @property
    def sharpness(self) -> float:
        """Anneals with pool order: soft while accreting, hard as it converges."""
        if self.rng.converged:
            return 1.0
        return min(1.0, len(self.pool) / 8.0)

    def evaluate_fill(self) -> FillState:
        """
        The Coherence Gate Axiom, vectorised:
        [Q|A / A|Q] === { Y=1 ; N != 1 ; Insult > 1 }
        with cross-plane disagreement as the false-fill detector.
        """
        self.rng.tick()
        active = self.coherence.active
        if not active:
            self.state = FillState.ACCRETING
            return self.state

        eps = 1e-9  # float guard: 1.00 - 0.70 is not exactly 0.30
        # The Fractal Ratio Protocol: R_net = 1 / product(scores).
        # NOT a mean. A mean cannot diverge; the fractal ratio goes to infinity
        # when any single plane collapses to zero, which is exactly the failure
        # this gate exists to catch. Using the mean here was a real bug.
        net = FieldMath_fractal_ratio(list(active.values()))
        in_band = (1.0 - self.tolerance - eps) <= net <= (1.0 + self.tolerance + eps)
        agree = self.coherence.disagreement <= self.tolerance * 2 + eps

        if in_band and agree and self.rng.converged:
            self.state = FillState.FILLED          # === : Y = 1 (TRUTH)
        elif in_band and not agree:
            self.state = FillState.FALSE_FILL      # planes disagree: stealth
        elif net > 1.0 + self.tolerance:
            self.state = FillState.FALSE_FILL      # Insult > 1 (CHAOS)
        else:
            self.state = FillState.ACCRETING       # N != 1, keep pulling
        return self.state

    # --- Staircase gate: a step must fill before it overflows. ---
    def drill_into(self, nxt: Plane) -> Optional["TruthState"]:
        if self.state != FillState.FILLED:
            raise RuntimeError(
                f"Staircase gating violated: step must fill before it overflows "
                f"(state={self.state.value}, address={self.address})"
            )
        if self.address.depth >= self.budget:
            self.state = FillState.FUNDAMENTAL  # TBE by budget exhaustion
            return None
        child = TruthState(address=self.address.drill(nxt),
                           budget=self.budget, tolerance=self.tolerance,
                           parent=self)
        # The child's addressable universe IS the parent's accreted pool.
        self.children.append(child)
        return child

    # --- Up-channel: never-fills and false-fills escalate and widen. ---
    def escalate(self) -> Optional["TruthState"]:
        if self.parent is None:
            self.state = FillState.NEVER_FILLED
            return None
        self.parent.state = FillState.ACCRETING  # reopen and widen the parent hole
        return self.parent


# ---------------------------------------------------------------------------
# PARALLAX: detection as intersection of independent projections.
#
# Pixel-motion-voxel-projection, mapped. Each observer (plane / language /
# model) casts a constraint ray rather than a verdict. Material earns its place
# only where rays from independent vantages intersect. One-ray content is
# stealth: plausible from a single vantage, unsupported from any other.
# ---------------------------------------------------------------------------

@dataclass
class Ray:
    observer: str          # which vantage cast it
    plane: Plane           # which camera position
    target: str            # the voxel: a canonical coordinate string
    strength: float = 1.0


def intersect(rays: Sequence[Ray], min_observers: int = 2
              ) -> List[Tuple[str, int, float, List[Plane]]]:
    """
    Returns [(target, distinct_observer_count, summed_strength, planes)]
    sorted by observer count then strength. Noise casts rays too, but random
    rays are statistically incapable of co-intersecting from independent
    vantages, so noise self-filters without a denoising step.
    """
    buckets: Dict[str, List[Ray]] = {}
    for r in rays:
        buckets.setdefault(r.target, []).append(r)

    out = []
    for target, rs in buckets.items():
        observers = {r.observer for r in rs}
        if len(observers) < min_observers:
            continue
        planes = sorted({r.plane for r in rs})
        out.append((target, len(observers), sum(r.strength for r in rs), planes))

    out.sort(key=lambda t: (-t[1], -t[2]))
    return out


def depth_map(rays: Sequence[Ray]) -> Dict[str, float]:
    """
    Stereo bonus: displacement between vantage readings estimates depth.
    Low variance across observers = deep, load-bearing, near the basin floor.
    High variance = shallow, vantage-dependent, near the surface.
    """
    buckets: Dict[str, List[float]] = {}
    for r in rays:
        buckets.setdefault(r.target, []).append(r.strength)
    out = {}
    for target, vals in buckets.items():
        if len(vals) < 2:
            out[target] = 0.0
            continue
        mean = sum(vals) / len(vals)
        var = sum((v - mean) ** 2 for v in vals) / len(vals)
        out[target] = 1.0 / (1.0 + var)  # 1.0 = perfect agreement = deepest
    return out
