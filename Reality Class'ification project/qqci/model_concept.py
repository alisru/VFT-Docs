def compare(a: Concept, b: Concept) -> str:
    va, vb = a.vector(), b.vector()
    lines = [f"  {a.word.upper()} vs {b.word.upper()}"]
    for i, k in enumerate(ORDER):
        d = vb[i] - va[i]
        mark = "  <-- the difference" if abs(d) > 0.25 else ""
        lines.append(f"    {VECTORS[i].interrogative:<7}"
                     f"{va[i]:5.2f} -> {vb[i]:5.2f}  ({d:+.2f}){mark}")
    lines.append(f"    R_net {a.r_net():.4f} -> {b.r_net():.4f}")
    lines.append(f"    distance {float(np.linalg.norm(vb - va)):.4f}")
    return "\n".join(lines)


